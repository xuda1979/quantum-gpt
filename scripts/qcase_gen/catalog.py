def build_catalog():
    cat = []
    seed = [10]

    def nxt():
        seed[0] += 1
        return seed[0]

    # ---- 40 QAOA cases: 8 problem types x N=4..8 ----
    for n in range(4, 9):
        d, nd, g = MAXCUT[n]
        cat.append(lambda n=n, d=d, nd=nd, g=g, s=nxt(): Q.maxcut(n, s, d, nd, g))
    for n in range(4, 9):
        d, nd, g = MIS[n]
        cat.append(lambda n=n, d=d, nd=nd, g=g, s=nxt(): Q.max_independent_set(n, s, d, nd, g))
    for n in range(4, 9):
        d, nd, g = NUMPART[n]
        cat.append(lambda n=n, d=d, nd=nd, g=g, s=nxt(): Q.number_partition(n, s, d, nd, g))
    for n in range(4, 9):
        k, d, nd, g = PORTFOLIO[n]
        cat.append(lambda n=n, k=k, d=d, nd=nd, g=g, s=nxt(): C.portfolio(n, k, s, d, nd, g))
    for n in range(4, 9):
        d, nd, g = KNAPSACK[n]
        cat.append(lambda n=n, d=d, nd=nd, g=g, s=nxt(): C.knapsack(n, s, d, nd, g))
    for n in range(4, 9):
        d, nd, g = VCOVER[n]
        cat.append(lambda n=n, d=d, nd=nd, g=g, s=nxt(): C.vertex_cover(n, s, d, nd, g))
    for n in range(4, 9):
        d, nd, g = MAX2SAT[n]
        cat.append(lambda n=n, d=d, nd=nd, g=g, s=nxt(): C.max2sat(n, s, d, nd, g))
    for n in range(4, 9):
        d, nd, g = LOADBAL[n]
        cat.append(lambda n=n, d=d, nd=nd, g=g, s=nxt(): C.task_assignment(n, s, d, nd, g))

    # ---- VQE: 2 molecules + TFIM N=2..6 + Heisenberg N=2..6 = 12 ----
    cat.append(
        lambda: V.h2(
            "量子化学与材料模拟",
            "求解氢分子 $H_2$ 在平衡键长附近的基态能量。",
            "用 VQE 逼近 $H_2$ 哈密顿量最小本征值。",
        )
    )
    cat.append(
        lambda: V.hehp(
            "量子化学与材料模拟",
            "求解氦氢离子 $HeH^{+}$ 的基态能量。",
            "用 VQE 逼近 $HeH^{+}$ 哈密顿量最小本征值。",
        )
    )
    for i, n in enumerate([2, 3, 4, 5, 6]):
        cat.append(
            lambda n=n, s=90 + i: V.tfim(
                n,
                s,
                "凝聚态与量子多体",
                f"求解 {n} 自旋横场 Ising 链的基态能量。",
                "用 VQE 逼近横场 Ising 链基态能量。",
            )
        )
    for i, n in enumerate([2, 3, 4, 5, 6]):
        cat.append(
            lambda n=n, s=95 + i: V.heisenberg(
                n,
                s,
                "凝聚态与量子磁性",
                f"求解 {n} 自旋各向同性 Heisenberg 链的基态能量。",
                "用 VQE 逼近 Heisenberg 链基态能量。",
            )
        )

    # ---- VQC: 10 (n x reps combos) ----
    for i, (n, reps) in enumerate(
        [(2, 1), (2, 2), (2, 3), (3, 1), (3, 2), (3, 3), (4, 1), (4, 2), (4, 3), (5, 2)]
    ):
        cat.append(
            lambda n=n, reps=reps, s=100 + i: A.vqc(
                n,
                reps,
                s,
                "量子机器学习",
                f"用 {n} 比特变分量子分类器（{reps} 层 Ansatz）对二维两类样本做监督分类。",
                "训练 VQC 达到高训练准确率。",
            )
        )

    # ---- QPE: 19 distinct phases ----
    qpe_ctx = [
        (2, 1, 4),
        (2, 3, 4),
        (3, 1, 8),
        (3, 3, 8),
        (3, 5, 8),
        (3, 7, 8),
        (4, 1, 16),
        (4, 3, 16),
        (4, 5, 16),
        (4, 7, 16),
        (4, 9, 16),
        (4, 11, 16),
        (4, 13, 16),
        (4, 15, 16),
        (5, 5, 32),
        (5, 11, 32),
        (5, 21, 32),
        (5, 27, 32),
        (5, 31, 32),
    ]
    for nc, num, den in qpe_ctx:
        cat.append(
            lambda nc=nc, num=num, den=den: A.qpe(
                nc,
                num,
                den,
                "谱估计与本征值",
                f"估计相位门 $\\varphi={num}/{den}$ 的相位。",
                "用 QPE 精确读出给定相位。",
            )
        )

    # ---- Grover: 19 distinct targets ----
    grover_ctx = [
        (2, "01"),
        (2, "10"),
        (2, "11"),
        (3, "000"),
        (3, "001"),
        (3, "010"),
        (3, "101"),
        (3, "110"),
        (3, "111"),
        (4, "0000"),
        (4, "0110"),
        (4, "1001"),
        (4, "1011"),
        (4, "1111"),
        (5, "00000"),
        (5, "10101"),
        (5, "01010"),
        (5, "11111"),
        (5, "10010"),
    ]
    for n, marked in grover_ctx:
        cat.append(
            lambda n=n, marked=marked: A.grover(
                n,
                marked,
                "无结构搜索",
                f"在 $2^{{{n}}}$ 个候选中用 Grover 搜索标记态 {marked}。",
                "用 Grover 振幅放大命中目标。",
            )
        )

    return cat
